export type Lang = "en" | "tr";
export type Key = keyof Dict;
const dicts: Record<Lang, Dict> = { en, tr };

export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("cortex.lang");
    if (saved === "en" || saved === "tr") return saved;
  } catch {
    // storage blocked: fall back to the browser language
  }
  return navigator.language.toLowerCase().startsWith("tr") ? "tr" : "en";
}

export const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "en", setLang: () => {} });

export function useT() {
  const { lang } = useContext(LangContext);
  return (k: Key) => dicts[lang][k] ?? en[k];
}

export function timeAgo(iso: string, t: (k: Key) => string): string {
  const s = Math.max(0, (Date.now() - Date.parse(iso)) / 1000);
  if (s < 45) return t("time.now");
  if (s < 3600) return `${Math.round(s / 60)} ${t("time.m")}`;
  if (s < 86400) return `${Math.round(s / 3600)} ${t("time.h")}`;
  return `${Math.round(s / 86400)} ${t("time.d")}`;
}
